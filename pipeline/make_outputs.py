def lab(m):
    return LABEL.get(m, m)


def style(ax):
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.grid(axis="y", color=C["grid"], linewidth=0.5)
    ax.set_axisbelow(True)


def save(fig, name):
    fig.savefig(FIG / f"{name}.pdf", bbox_inches="tight")
    fig.savefig(FIG / f"{name}.png", dpi=350, bbox_inches="tight")
    plt.close(fig)


def tex_table(name, caption, label, colspec, header, rows, note=None, wide=False):
    env = "table*" if wide else "table"
    body = "\n".join(rows)
    fn = f"% Auto-generated by pipeline_v2/make_outputs.py -- do not hand-edit.\n\\begin{{{env}}}[!t]\n\\centering\n" \
         f"\\caption{{{caption}}}\n\\label{{{label}}}\n\\setlength{{\\tabcolsep}}{{3pt}}\\small\n" \
         f"\\begin{{tabular}}{{{colspec}}}\n\\toprule\n{header} \\\\\n\\midrule\n{body}\n\\bottomrule\n\\end{{tabular}}\n"
    if note:
        fn += f"\\par\\smallskip\\parbox{{0.95\\linewidth}}{{\\footnotesize {note}}}\n"
    fn += f"\\end{{{env}}}\n"
    (TEX / f"{name}.tex").write_text(fn)


