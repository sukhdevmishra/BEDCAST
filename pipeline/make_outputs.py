def f_skill(pm, mcs):
    ev = pm[pm.period == "evaluation"]
    mc = mcs[mcs.period == "evaluation"]
    fig, ax = plt.subplots(figsize=(3.5, 2.8))
    x = np.arange(len(HORIZONS))
    highlight = {"SARIMA": C["comb"], "NaiveDOW": C["dow"], PRIMARY: C["primary"]}
    names = {"SARIMA": "SARIMA (best)", "NaiveDOW": "Naive + weekday", PRIMARY: "Stacking (EN-A)"}
    dodge = {"SARIMA": -0.07, "NaiveDOW": 0.0, PRIMARY: 0.07}
    others = [m for m in ev.model.unique() if m not in highlight and m not in ("Naive", "SeasonalNaive") and not m.endswith("-B")]
    for m in others:
        v = [ev[(ev.model == m) & (ev.h == h)].RelRMSE_naive.iloc[0] for h in HORIZONS]
        ax.plot(x, v, color=C["grey"], linewidth=0.7, alpha=0.55, zorder=1)
    ax.axhline(1.0, color=C["ink2"], linewidth=0.9, linestyle=(0, (4, 2)), zorder=2)
    ax.text(-0.25, 1.0015, "Naive", va="bottom", fontsize=7, color=C["ink2"])
    ends = {}
    for m, col in highlight.items():
        v = np.array([ev[(ev.model == m) & (ev.h == h)].RelRMSE_naive.iloc[0] for h in HORIZONS])
        inm = np.array([bool(mc[(mc.model == m) & (mc.h == h)].in_MCS90.iloc[0]) for h in HORIZONS])
        xs = x + dodge[m]
        ax.plot(xs, v, color=col, linewidth=2, zorder=3)
        ax.scatter(xs[inm], v[inm], s=34, color=col, edgecolor="white", linewidth=1.2, zorder=4)
        ax.scatter(xs[~inm], v[~inm], s=34, facecolor="white", edgecolor=col, linewidth=1.5, zorder=4)
        ends[m] = v[-1]
    # end labels with a minimum vertical separation
    order = sorted(ends, key=ends.get)
    ypos, last = {}, -np.inf
    for m in order:
        ypos[m] = max(ends[m], last + 0.012)
        last = ypos[m]
    for m in order:
        near_naive = abs(ypos[m] - 1.0) < 0.006
        ax.text(x[-1] + 0.18, ypos[m] + (0.004 if near_naive else 0), names[m],
                va="bottom" if near_naive else "center", fontsize=7, color=C["ink"])
    ax.set_xticks(x, [f"{h}" for h in HORIZONS])
    ax.set_xlabel("Forecast horizon (days)")
    ax.set_ylabel("RMSE relative to naive")
    ax.set_xlim(-0.35, len(HORIZONS) - 0.3 + 1.0)
    style(ax)
    ax.text(0.0, -0.32, "Filled marker: in the 90% Model Confidence Set; hollow: excluded. Grey: other models.",
            transform=ax.transAxes, fontsize=6.5, color=C["ink2"])
    save(fig, "v2_skill_by_horizon")


def f_confirmatory(F, col=False):
    """col=True: the same two panels sized for one journal column (v2_confirmatory_forecasts_col)."""
    fs = 6 if col else None
    lw = 0.8 if col else 1.3
    fig, axes = plt.subplots(2, 1, figsize=(3.5, 2.45) if col else (7.16, 4.4), sharex=True)
    tg = np.arange(CONF_START, EVAL_END + 1)
