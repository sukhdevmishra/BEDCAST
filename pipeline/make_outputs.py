def f_attribution(nn):
    """Neural learners' signed grouped permutation importance, positive parts normalised per model and
    averaged over the five architectures, by horizon."""
    bands = [("Lag 1", ["1"]), ("Lag 2", ["2"]), ("Lags 3-7", ["3-7"]), ("Lags 8-28", ["8-14", "15-28"]),
             ("Lags 29-90", ["29-56", "57-90"])]
    fig, ax = plt.subplots(figsize=(3.5, 2.2))
    for i, h in enumerate(HORIZONS):
        shares = []
        for m in BASE_NN:
            s = nn[(nn.model == m) & (nn.h == h)].set_index("group").delta_MSE.clip(lower=0)
            shares.append(s / s.sum())
        p = pd.concat(shares, axis=1).mean(axis=1)
        left = 0.0
        for (name, gs), col in zip(bands, RAMP):
            v = float(sum(p.get(g, 0.0) for g in gs))
            ax.barh(i, v, left=left, color=col, edgecolor="white", linewidth=1, height=0.6)
            left += v
        v = float(p.get("DOW", 0.0))
        ax.barh(i, v, left=left, color=C["dow"], edgecolor="white", linewidth=1, height=0.6)
    ax.set_yticks(range(len(HORIZONS)), [f"h = {h}" for h in HORIZONS])
    ax.invert_yaxis()
    ax.set_xlabel("Share of positive permutation importance")
    ax.set_xlim(0, 1.0)
    for s_ in ("top", "right"):
        ax.spines[s_].set_visible(False)
    handles = [plt.Rectangle((0, 0), 1, 1, color=c) for c in RAMP + [C["dow"]]]
    ax.legend(handles, [b[0] for b in bands] + ["Weekday"], ncol=3, frameon=False, fontsize=6.5,
              loc="upper center", bbox_to_anchor=(0.5, -0.3))
    save(fig, "v2_attribution")


