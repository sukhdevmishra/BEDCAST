def t_exceed_compare(pb, p90):
    """Supplement: BSS at the capacity threshold next to the originally specified 90th-percentile threshold."""
    rows = []
    for h in HORIZONS:
        for m in ["Naive", "NaiveDOW", "Comb", "SARIMA", "ETS", PRIMARY]:
            cells = []
            for d in (pb, p90):
                for per in ("evaluation", "confirmatory"):
                    cells.append(f"{d[(d.h == h) & (d.model == m) & (d.period == per)].brier_skill_vs_clim.iloc[0]:+.3f}")
            rows.append(f"{h} & {lab(m)} & " + " & ".join(cells) + " \\\\")
        if h != HORIZONS[-1]:
            rows.append("\\midrule")
    def desc(d):
        e = d[d.period == "evaluation"].iloc[0]
        c = d[d.period == "confirmatory"].iloc[0]
        return e.threshold_beds, 100 * e.event_rate, 100 * c.event_rate
    t1, e1, c1 = desc(pb)
    t2, e2, c2 = desc(p90)
    tex_table("v2_exceed_thresholds", "Brier skill score of exceedance probabilities at the capacity-based and the originally specified thresholds.",
              "tab:v2_exceed_thresholds", "c l cc cc",
              f"& & \\multicolumn{{2}}{{c}}{{$>{t1:.2f}$ beds ({100 * EXCEED_RATE:.0f}\\% of {BED_CAPACITY})}} & "
              f"\\multicolumn{{2}}{{c}}{{$>{t2:.1f}$ beds (original)}} \\\\\n$h$ & Model & Eval. & Conf. & Eval. & Conf.", rows,
              note=f"BSS relative to the climatological exceedance rate (positive = better than climatology). Event frequency: "
                   f"{e1:.1f}\\% of evaluation and {c1:.1f}\\% of confirmatory days above {t1:.2f} beds; {e2:.1f}\\% and {c2:.1f}\\% above "
                   f"{t2:.1f} beds (the 90th percentile of pre-2017 occupancy). Occupancy never exceeded the sanctioned "
                   f"capacity of {BED_CAPACITY} beds (maximum {load_series()[1].max():.0f}). The primary threshold was adopted after the results had been examined.")


def t_stability(gr, sw):
    rows = []
    for h in HORIZONS:
        g = gr[gr.h == h]
        cells = [f"{r.max_abs_fluctuation:.2f}{'$^*$' if r.reject_stability else ''}" for _, r in g.iterrows()]
        s = sw[sw.h == h]
        bias = [f"{r.p_holm:.3f}" for _, r in s.iterrows()]
        rows.append(f"{h} & " + " & ".join(cells) + " & " + " & ".join(bias) + " \\\\")
    crit = gr.critical_5pct_mu0_3.iloc[0] if "critical_5pct_mu0_3" in gr else gr.iloc[0, 3]
    short = {"Naive": "Naive", "NaiveDOW": "N+wk", "Comb": "Comb", "SARIMA": "SARIMA", "ETS": "ETS", PRIMARY: "EN-A"}
    models = [short.get(m, m) for m in sw[sw.h == HORIZONS[0]].model]
    tex_table("v2_stability", "Stability diagnostics over the evaluation span.", "tab:v2_stability",
              "c ccc " + "c" * len(models),
              "$h$ & \\multicolumn{3}{c}{Fluctuation: EN-A vs.} & \\multicolumn{" + str(len(models)) +
              "}{c}{Bias-shift test, Holm-adjusted $p$} \\\\\n & Naive & N+wk & Comb & " + " & ".join(models),
              rows, wide=True,
              note=f"EN-A: stacking ensemble (ElasticNet, Variant A); N+wk: naive with day-of-week drift. Left: Giacomini--Rossi fluctuation statistic (window 30\\% of the span) for the relative squared-error loss; "
                   f"$^*$ exceeds the simulated 5\\% critical value ({crit:.2f}). Right: HAC-robust sup-Wald test for a single shift in "
                   f"the mean forecast error (trimming 15\\%), $p$-values from the simulated limit distribution, Holm-adjusted across models.")


def t_weights(mw, prop):
    rows = []
    for h in HORIZONS:
        w = mw[(mw.h == h)]
        w = w[w.R >= w.R.min()]
        mean = w[BASE_ALL + ["persistence"]].mean()
        cells = " & ".join(f"{mean[m]:+.2f}" for m in BASE_ALL + ["persistence"])
        rows.append(f"{h} & {cells} \\\\")
    tex_table("v2_meta_weights", "Effective combination weights of the stacking ensemble (ElasticNet, Variant A), averaged over refits.",
              "tab:v2_weights", "c " + "r" * (len(BASE_ALL) + 1),
              "$h$ & " + " & ".join(BASE_ALL) + " & Persistence", rows, wide=True,
              note="The ensemble forecast is $y_o + b + \\sum_j w_j (\\hat y^{(j)} - y_o)$, so the weights $w_j$ and the persistence "
                   "weight $1-\\sum_j w_j$ sum to one. A persistence weight near one means the combiner converges to the naive forecast.")


