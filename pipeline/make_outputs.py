def t_accuracy(pm, mcs, period, name, label, caption):
    ev = pm[pm.period == period]
    mc = mcs[mcs.period == period] if period in mcs.period.unique() else None
    groups = [("Benchmarks", ["Naive", "NaiveDOW", "SeasonalNaive", "Comb"]),
              ("Base learners", BASE_ALL), ("Stacking, Variant A", [f"{m}-A" for m in META])]
    rows = []
    naive_rmse = " & ".join(f"{ev[(ev.model == 'Naive') & (ev.h == h)].RMSE.iloc[0]:.2f}" for h in HORIZONS)
    rows.append(f"\\multicolumn{{1}}{{l}}{{\\emph{{Naive RMSE (beds)}}}} & {naive_rmse} \\\\")
    for gname, ms in groups:
        rows.append(f"\\midrule\n\\multicolumn{{5}}{{l}}{{\\textbf{{{gname}}}}} \\\\")
        for m in ms:
            cells = []
            for h in HORIZONS:
                v = ev[(ev.model == m) & (ev.h == h)].RelRMSE_naive.iloc[0]
                inm = mc is not None and bool(mc[(mc.model == m) & (mc.h == h)].in_MCS90.iloc[0])
                best = v == ev[ev.h == h].RelRMSE_naive.min()
                s = f"{v:.3f}"
                s = f"\\textbf{{{s}}}" if best else s
                cells.append(s + ("$^\\dagger$" if inm else ""))
            rows.append(f"{lab(m)} & " + " & ".join(cells) + " \\\\")
    tex_table(name, caption, label, "l cccc", "Model & $h=1$ & $h=7$ & $h=14$ & $h=28$", rows,
              note="Entries are RMSE relative to the naive forecast (below 1 = better than naive). "
                   "Bold: best at that horizon. $^\\dagger$: member of the 90\\% Model Confidence Set.")


def t_primary(pr):
    rows = []
    for _, r in pr.iterrows():
        comp = r.comparison.replace(f"{PRIMARY} vs ", "vs ").replace("NaiveDOW", "Naive + weekday")
        rows.append(f"{int(r.h)} & {comp} & {r.test.split(' (')[0]} & {r.stat:.2f} & {r.p:.3f} & {r.p_holm:.3f} & "
                    f"{r.mean_sq_loss_diff_primary_minus_bench:+.2f} & {r.conf_mean_sq_loss_diff:+.2f} & "
                    f"{'Yes' if r.claim_supported else 'No'} \\\\")
    tex_table("v2_primary_comparisons",
              "Pre-specified primary comparisons of the stacking ensemble (ElasticNet, Variant A) over the evaluation span (2017-04-02 to 2020-03-24).",
              "tab:v2_primary", "c l l rrr rr c",
              "$h$ & Comparison & Test & Stat. & $p$ & $p_{\\mathrm{Holm}}$ & $\\Delta$MSE & $\\Delta$MSE$_{\\mathrm{conf}}$ & Claim",
              rows, wide=True,
              note="$\\Delta$MSE = mean squared-error loss of the ensemble minus that of the comparator (negative = ensemble better), "
                   "over the evaluation span and the confirmatory period (2019-10-04 to 2020-03-24). A claim requires Holm-adjusted $p<0.05$ "
                   "and the same sign in the confirmatory period. Clark--West is one-sided (the naive forecast is nested); DM tests are "
                   "two-sided with Newey--West variance and the HLN correction.")


